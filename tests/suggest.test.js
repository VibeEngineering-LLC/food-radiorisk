// #FR-36: подсказка названия продукта — чистый список и фильтр по началу слова
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { cleanProductNames, filterNames } from '../src/ui/suggest.js';
const yes = () => true;

test('чистка: латынь в скобках, группы и служебные строки, регистр, дубли', () => {
  const raw = ['Агроцибе (Agrocybe aegerita)', 'аккумуляторы радиоцезия: польский гриб', 'грибы сильнонакапливающие', 'Розитес (колпак кольчатый',
    'голубика', 'Лисичка', 'лисичка', 'Коэффициент перехода Cs-137 из почвы в грибы', 'свежие лесные ягоды (вид не назван)', 'Сено многолетних злаковых трав'];
  assert.deepEqual(cleanProductNames(raw, yes), ['Агроцибе', 'Голубика', 'Лисичка', 'Розитес', 'Свежие лесные ягоды']);
});

test('чистка: не продукт (по каталогу) — отбрасывается; дополнительные названия добавляются', () => {
  assert.deepEqual(cleanProductNames(['Берёза', 'Черника'], n => n !== 'Берёза', ['Молоко']), ['Молоко', 'Черника']);
});

test('фильтр: начало названия, затем начало слова; прочее — нет', () => {
  assert.deepEqual(filterNames(['Белый гриб', 'Смородина чёрная', 'Черника', 'Ежевика'], 'чер'), ['Черника', 'Смородина чёрная']);
  assert.deepEqual(filterNames(['Черника', 'Ежевика'], ''), ['Черника', 'Ежевика']);
  assert.equal(filterNames(Array.from({ length: 30 }, (_, i) => `Гриб ${i}`), 'гр').length, 12);
});
